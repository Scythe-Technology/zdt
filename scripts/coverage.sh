# Generate a line-coverage report for the zdt test suite using kcov.
#
# Why this script exists:
#   kcov can only map execution back to source lines when the binary carries
#   DWARF line tables it can parse. Zig's *native* x86_64 backend (the default
#   for `-O Debug`) emits line tables kcov cannot read (it reports ~0% covered).
#   Forcing the LLVM backend with `-fllvm` produces standard DWARF that kcov
#   parses correctly. This script therefore builds the test binaries with
#   `-fllvm` and runs each under kcov, then merges the runs.
#
# The test binaries are built directly with `zig test` (not `zig build test`),
# reproducing the module setup from build.zig on the CLI:
#   - the `zdt` module rooted at lib/root.zig
#   - the auto-generated `tzdb_prefix` anonymous import (needed by lib/Timezone.zig)
#   - libc linked (-lc), matching build.zig
#
# Usage:
#   bash scripts/coverage.sh            # write report to ./coverage
#   bash scripts/coverage.sh --help     # show help and exit
#   OUT_DIR=/tmp/cov bash scripts/coverage.sh
#
# Environment variables (all optional):
#   ZIG         zig executable                  (default: zig)
#   KCOV        kcov executable                 (default: kcov)
#   TZDB_PREFIX path to system IANA tzdb        (default: /usr/share/zoneinfo/)
#   LOCALE      LC_TIME value for locale tests  (default: en_US.UTF-8)
#   OUT_DIR     where to write the report       (default: <repo>/coverage)
#   WORK_DIR    scratch dir for binaries/runs   (default: a fresh tmpdir)
#   KEEP_WORK   set to 1 to keep the scratch dir (default: 0)
#
# Requirements: zig (master), kcov >= 40, python3 (only for the summary print).

set -euo pipefail

print_help() {
    cat <<'HELP'
Usage: bash scripts/coverage.sh [-h|--help]

Generate a line-coverage report for the zdt test suite using kcov.

The test binaries are built with Zig's LLVM backend (-fllvm) because kcov cannot
parse the DWARF line tables emitted by Zig's native x86_64 backend. Each binary
is run under kcov, then all runs are merged into a single report scoped to lib/.

The test binaries are built directly with `zig test` (not `zig build test`),
reproducing the module setup from build.zig on the CLI (the `zdt` module, the
auto-generated `tzdb_prefix` anonymous import, and libc).

Options:
  -h, --help   show this help message and exit

Environment variables (all optional):
  ZIG          zig executable                   (default: zig)
  KCOV         kcov executable                  (default: kcov)
  TZDB_PREFIX  path to system IANA tzdb         (default: /usr/share/zoneinfo/)
  LOCALE       LC_TIME value for locale tests   (default: en_US.UTF-8)
  OUT_DIR      where to write the report        (default: <repo>/coverage)
  WORK_DIR     scratch dir for binaries/runs    (default: a fresh tmpdir)
  KEEP_WORK    set to 1 to keep the scratch dir (default: 0)

Requirements:
  zig (master), kcov >= 40, python3 (only for the summary print)

Output:
  Browsable HTML report at <OUT_DIR>/index.html
  Machine-readable <OUT_DIR>/cobertura.xml

Examples:
  bash scripts/coverage.sh
  OUT_DIR=/tmp/cov bash scripts/coverage.sh
  TZDB_PREFIX=/usr/share/zoneinfo/ LOCALE=en_US.UTF-8 bash scripts/coverage.sh
HELP
}

# show help before any tool checks so it works without zig/kcov installed
case "${1:-}" in
    -h | --help | help) print_help; exit 0 ;;
esac

ZIG="${ZIG:-zig}"
KCOV="${KCOV:-kcov}"
TZDB_PREFIX="${TZDB_PREFIX:-/usr/share/zoneinfo/}"
LOCALE="${LOCALE:-en_US.UTF-8}"
KEEP_WORK="${KEEP_WORK:-0}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
OUT_DIR="${OUT_DIR:-$REPO_ROOT/coverage}"

# --- sanity checks -----------------------------------------------------------
command -v "$ZIG" >/dev/null 2>&1 || { echo "error: '$ZIG' not found in PATH" >&2; exit 1; }
command -v "$KCOV" >/dev/null 2>&1 || { echo "error: '$KCOV' not found in PATH (install kcov >= 40)" >&2; exit 1; }

# --- scratch dir -------------------------------------------------------------
if [[ -z "${WORK_DIR:-}" ]]; then
    WORK_DIR="$(mktemp -d -t zdt-cov-XXXXXX)"
fi
mkdir -p "$WORK_DIR/bin" "$WORK_DIR/runs"
if [[ "$KEEP_WORK" != "1" ]]; then
    trap 'rm -rf "$WORK_DIR"' EXIT
fi

# --- generate the tzdb_prefix module (build.zig does this via a build step) ---
TZDB_PREFIX_FILE="$WORK_DIR/tzdb_prefix.zig"
{
    echo "// auto-generated by scripts/coverage.sh; mirrors build.zig's anonymous import."
    echo "pub const tzdb_prefix = \"$TZDB_PREFIX\";"
} > "$TZDB_PREFIX_FILE"

# --- helper: build one test binary with the LLVM backend ---------------------
build_binary() {
    local out="$1"
    shift
    # shellcheck disable=SC2086
    "$ZIG" test -fllvm --test-no-exec -femit-bin="$out" -lc "$@"
}

# --- collect test files (auto-discover tests/test_*.zig, like build.zig) -----
mapfile -t TEST_FILES < <(cd "$REPO_ROOT" && find tests -maxdepth 1 -name 'test_*.zig' -printf '%f\n' | sort)

build_ok=0
build_fail=0

echo ":: building test binaries with -fllvm (kcov needs LLVM DWARF line tables)"

# root test: runs the inline 'test {}' blocks in lib/*.zig
if build_binary "$WORK_DIR/bin/zdt_root" \
    --dep tzdb_prefix -Mroot="$REPO_ROOT/lib/root.zig" -Mtzdb_prefix="$TZDB_PREFIX_FILE"; then
    build_ok=$((build_ok + 1))
else
    echo "  !! failed: zdt_root (lib/root.zig)" >&2
    build_fail=$((build_fail + 1))
fi

# integration tests: each imports the 'zdt' module
for f in "${TEST_FILES[@]}"; do
    name="${f%.zig}"
    if build_binary "$WORK_DIR/bin/$name" \
        --dep zdt -Mroot="$REPO_ROOT/tests/$f" \
        --dep tzdb_prefix -Mzdt="$REPO_ROOT/lib/root.zig" \
        -Mtzdb_prefix="$TZDB_PREFIX_FILE"; then
        build_ok=$((build_ok + 1))
    else
        echo "  !! failed: $name (tests/$f)" >&2
        build_fail=$((build_fail + 1))
    fi
done

if [[ "$build_fail" -gt 0 ]]; then
    echo "error: $build_fail test binary(ies) failed to build; aborting" >&2
    exit 1
fi
echo "   built $build_ok test binaries -> $WORK_DIR/bin"

# --- run each binary under kcov ----------------------------------------------
echo ":: running tests under kcov (LC_TIME=$LOCALE so locale-specific tests run)"
for bin in "$WORK_DIR"/bin/*; do
    name="$(basename "$bin")"
    rm -rf "$WORK_DIR/runs/$name"
    # --include-pattern scopes kcov to our sources; merge later restricts again.
    if ! LC_TIME="$LOCALE" "$KCOV" --include-pattern="$REPO_ROOT/lib/" \
        "$WORK_DIR/runs/$name" "$bin" >/dev/null 2>&1; then
        echo "   !! kcov failed for $name (rerun without this script to inspect)" >&2
        exit 1
    fi
    echo "   $(basename "$bin") done"
done

# --- merge all runs into one report ------------------------------------------
echo ":: merging coverage runs"
rm -rf "$WORK_DIR/merged"
"$KCOV" --merge --include-pattern="$REPO_ROOT/lib/" \
    "$WORK_DIR/merged" "$WORK_DIR"/runs/* >/dev/null 2>&1

MERGED="$WORK_DIR/merged/kcov-merged"
if [[ ! -d "$MERGED" ]]; then
    echo "error: merge produced no report at $MERGED" >&2
    exit 1
fi

# --- publish the report ------------------------------------------------------
rm -rf "$OUT_DIR"
cp -r "$MERGED" "$OUT_DIR"

# --- print a summary ---------------------------------------------------------
SUMMARY="$OUT_DIR/coverage.json"
COBERTURA="$OUT_DIR/cobertura.xml"

echo
echo "================ zdt coverage summary ================"
if command -v python3 >/dev/null 2>&1 && [[ -f "$SUMMARY" ]]; then
    python3 - "$SUMMARY" "$COBERTURA" <<'PY'
import json, sys
summary, cobertura = sys.argv[1], sys.argv[2]
d = json.load(open(summary))
cl = int(d["covered_lines"]); tl = int(d["total_lines"])
pct = 100.0 * cl / tl if tl else 0.0
print(f"overall: {cl}/{tl} lines = {pct:.2f}%  ({len(d['files'])} files with executable code)\n")
print(f"{'file':<34}{'cov':>8}{'total':>8}{'pct':>9}")
print("-" * 59)
for f in sorted(d["files"], key=lambda x: x["file"]):
    c = int(f["covered_lines"]); t = int(f["total_lines"])
    p = 100.0 * c / t if t else 0.0
    # strip everything up to and including "/lib/" so the path is repo-relative
    name = f["file"].split("/lib/", 1)[1] if "/lib/" in f["file"] else f["file"]
    print(f"{name:<34}{c:>8}{t:>8}{p:>8.2f}%")

# uncovered lines per file (from cobertura.xml)
import xml.etree.ElementTree as ET
try:
    root = ET.parse(cobertura).getroot()
    uncov_by_file = {}
    for cls in root.findall(".//class"):
        fn = cls.get("filename", "")
        uncov = [int(l.get("number")) for l in cls.findall("lines/line") if l.get("hits") == "0"]
        if uncov:
            uncov_by_file[fn] = uncov
    if uncov_by_file:
        print("\nuncovered lines:")
        total_u = 0
        for fn in sorted(uncov_by_file):
            u = uncov_by_file[fn]
            total_u += len(u)
            print(f"  {fn}: {u}")
        print(f"  total uncovered: {total_u}")
except Exception:
    pass
PY
else
    echo "(install python3 for a per-file summary)"
fi
echo
echo "HTML report : $OUT_DIR/index.html"
echo "cobertura   : $OUT_DIR/cobertura.xml"
if [[ "$KEEP_WORK" == "1" ]]; then
    echo "scratch dir : $WORK_DIR (kept)"
fi
echo "======================================================"
